#!/usr/bin/env bash
#
# release.sh — pin the EXACT image set "shared to OCI" for a release so the
# local harness installs that release and not :latest.
#
# A release is not one version string; it is the set of image tags/digests for
# oci-proxy, vcp-worker and vlm-worker (plus the ONTAP line the VLM worker
# serves). This reads a small JSON manifest and writes an env file that the
# compose stack interpolates, so `set_release` becomes deterministic.
#
# Manifest shape (see release.example.json):
#   {
#     "release": "R9.19.1X-8138587",
#     "ontapVersion": "9.19.1X29",
#     "images": {
#       "ociProxy":  "iad.ocir.io/idqogasfjw45/oci-proxy:<tag>",
#       "vcpWorker": "iad.ocir.io/idqogasfjw45/vcp-worker:<tag>",
#       "vlmWorker": "iad.ocir.io/idqogasfjw45/vlm-worker:R9.19.1X-8138587"
#     }
#   }
#
# Subcommands:
#   apply <manifest.json>   Validate and write $WORKSPACE_ROOT/.oci-release.env
#   show                    Print the currently applied release env
#   env                     Print export lines (for `eval "$(release.sh env)"`)
#   verify                  Best-effort check that each image exists in the registry
#
# Exit codes: 0 ok, 2 usage/validation error.

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
# shellcheck source=lib.sh
. "$SCRIPT_DIR/lib.sh"

RELEASE_ENV_FILE="${OCI_RELEASE_ENV_FILE:-$WORKSPACE_ROOT/.oci-release.env}"

usage() { sed -n '2,38p' "${BASH_SOURCE[0]}" | sed 's/^# \{0,1\}//'; }

cmd_apply() {
  local manifest="${1:-}"
  [ -n "$manifest" ] || die "usage: release.sh apply <manifest.json>"
  [ -f "$manifest" ] || die "manifest not found: $manifest"
  have python3 || die "python3 is required to parse the manifest"

  # Parse + validate with python3; emit shell-safe KEY=VALUE lines.
  local parsed
  parsed="$(python3 - "$manifest" <<'PY'
import json, sys, shlex
m = json.load(open(sys.argv[1]))
imgs = m.get("images", {})
required = {
    "OCI_RELEASE":      m.get("release", ""),
    "OCI_ONTAP_VERSION": m.get("ontapVersion", ""),
    "OCI_PROXY_IMAGE":  imgs.get("ociProxy", ""),
    "VCP_WORKER_IMAGE": imgs.get("vcpWorker", ""),
    "VLM_WORKER_IMAGE": imgs.get("vlmWorker", ""),
}
missing = [k for k, v in required.items() if not v]
if missing:
    sys.stderr.write("manifest missing required fields: %s\n" % ", ".join(missing))
    sys.exit(2)
for k, v in required.items():
    print("%s=%s" % (k, shlex.quote(v)))
PY
)" || die "manifest validation failed"

  {
    echo "# Generated by release.sh apply on $(date -u +%Y-%m-%dT%H:%M:%SZ)"
    echo "# Source manifest: $manifest"
    echo "$parsed"
  } > "$RELEASE_ENV_FILE"

  ok "[release] wrote $RELEASE_ENV_FILE"
  cmd_show
}

cmd_show() {
  [ -f "$RELEASE_ENV_FILE" ] || die "no release applied yet (run: release.sh apply <manifest.json>)"
  info "[release] active release ($RELEASE_ENV_FILE):"
  grep -v '^#' "$RELEASE_ENV_FILE" | sed 's/^/  /' >&2
}

cmd_env() {
  [ -f "$RELEASE_ENV_FILE" ] || die "no release applied yet"
  grep -v '^#' "$RELEASE_ENV_FILE" | sed 's/^/export /'
}

cmd_verify() {
  [ -f "$RELEASE_ENV_FILE" ] || die "no release applied yet"
  # shellcheck disable=SC1090
  set -a; . "$RELEASE_ENV_FILE"; set +a
  local e rc=0; e="$(engine)"
  for var in OCI_PROXY_IMAGE VCP_WORKER_IMAGE VLM_WORKER_IMAGE; do
    local img="${!var}"
    printf '[release] checking %s … ' "$img" >&2
    # manifest inspect is the cheap registry check (no layer download); fall back
    # to a quiet pull for registries/setups where inspect is unavailable. Docker
    # has no `image exists` subcommand (that was a Podman-ism).
    if "$e" manifest inspect "$img" >/dev/null 2>&1 || "$e" pull -q "$img" >/dev/null 2>&1; then
      ok "found"
    else
      warn "NOT reachable (need registry login or wrong tag)"
      rc=1
    fi
  done
  return $rc
}

case "${1:-}" in
  apply)        shift; cmd_apply "$@" ;;
  show)         cmd_show ;;
  env)          cmd_env ;;
  verify)       cmd_verify ;;
  -h|--help|"") usage ;;
  *) die "unknown subcommand '$1' (use: apply | show | env | verify)" ;;
esac
